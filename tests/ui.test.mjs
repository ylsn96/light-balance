const submit = async selector => {
  for (const el of $(selector).elements) {
    if (el.disabled) continue;
    const validity = el.validity;
    for (const flag of ['badInput', 'customError', 'patternMismatch', 'rangeOverflow', 'rangeUnderflow', 'tooLong', 'tooShort', 'typeMismatch', 'valueMissing']) assert.equal(validity[flag], false, `${el.name}: ${flag}`);
    // Happy DOM checks floating-point remainders without the HTML step-base tolerance.
    if (el.type === 'number' && el.value !== '' && el.step && el.step !== 'any') {
      const steps = (Number(el.value) - Number(el.min || 0)) / Number(el.step);
      assert.ok(Math.abs(steps - Math.round(steps)) < 1e-7, `${el.name}: step mismatch`);
    }
  }
  $(selector).dispatchEvent(new window.Event('submit', { bubbles: true, cancelable: true }));
  await new Promise(setImmediate);
};
